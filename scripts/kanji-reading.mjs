// Writes src/lib/kanjiReading.js: how often each kanji appears in four kinds
// of Japanese text, for coverage's Reading measure. Run it rather than
// editing the output:
//
//   node scripts/kanji-reading.mjs
//
// The counts are scriptin's kanji-frequency, 2015 datasets
// (github.com/scriptin/kanji-frequency, CC BY 4.0) — the same ones wkstats
// reads. Each corpus becomes every kanji's share of all the kanji in it, in
// parts per million, and only kanji at one part per million or more in some
// corpus are kept: the rest come to under 0.05% of any corpus.

import { writeFileSync } from 'node:fs'

const SOURCE = 'https://raw.githubusercontent.com/scriptin/kanji-frequency/master/data2015'
// [file, the name the board gives it, the source under the name] — from
// the dataset's own description of each corpus.
const CORPORA = [
  ['news', 'newspapers', 'Asahi, Mainichi, Yomiuri, Saga Shimbun · 2014–15'],
  ['twitter', 'tweets', 'one week of Twitter’s public sample · June 2015'],
  ['wikipedia', 'Wikipedia', 'every Japanese page · May 2015'],
  ['aozora', 'old books', 'Aozora Bunko, out of copyright · mostly before 1950']
]
const FLOOR = 1

const shares = []
for (const [file] of CORPORA) {
  const response = await fetch(`${SOURCE}/${file}.json`)
  if (!response.ok) throw new Error(`${file}: ${response.status}`)
  // [["all", total, 1], [kanji, count, fraction], …]
  const [[, total], ...rows] = await response.json()
  shares.push(new Map(rows.map(([kanji, count]) => [kanji, Math.round((count / total) * 1e6)])))
}

// Every kept kanji, most used first across the four.
const kept = [...new Set(shares.flatMap(m => [...m.keys()]))]
  .filter(k => shares.some(m => (m.get(k) ?? 0) >= FLOOR))
  .sort((a, b) => shares.reduce((s, m) => s + (m.get(b) ?? 0), 0) - shares.reduce((s, m) => s + (m.get(a) ?? 0), 0))

const lines = CORPORA.map(([, name, source], i) => `  ['${name}', '${source}', [${kept.map(k => shares[i].get(k) ?? 0).join(',')}]]`)

writeFileSync(
  new URL('../src/lib/kanjiReading.js', import.meta.url),
  `// How often each kanji appears in four kinds of Japanese text — the Reading
// measure in coverage. Generated by scripts/kanji-reading.mjs; regenerate
// rather than hand-edit.
//
// From scriptin's kanji-frequency, 2015 datasets
// (github.com/scriptin/kanji-frequency), CC BY 4.0, collected in 2015:
// online news from various sources, Twitter, Japanese Wikipedia, and
// fiction and non-fiction from Aozora Bunko. Each number is that
// kanji's share of every kanji in the corpus, in parts per million, in the
// order of KANJI; each corpus is [name, source, shares].

export const KANJI = '${kept.join('')}'

export const READING = [
${lines.join(',\n')}
]
`
)
console.log(`${kept.length} kanji`)
